    def _get_employer_contributions(self, payslip):
        """
        Aportaciones patronales para la boleta.
        Ajusta los códigos según tus reglas reales.
        """
        return {
            'sctr': self._sum_line_codes(payslip, ['SCTR', 'APORTE_SCTR']),
            'essalud': self._sum_line_codes(payslip, ['APORTE_ESSALUD', 'ESSALUD']),
            'senati': self._sum_line_codes(payslip, ['SENATI', 'APORTE_SENATI']),
            'eps': self._sum_line_codes(payslip, ['EPS', 'APORTE_EPS']),
        }


    def _get_totals(self, payslip, earnings, deductions):
        """
        Totales principales de la boleta.
        Prioriza líneas oficiales GROSS y NET.
        """
        currency = payslip.company_id.currency_id

        total_earnings = self._sum_line_codes(payslip, ['GROSS'])
        net_amount = self._sum_line_codes(payslip, ['NET'])

        if currency.is_zero(total_earnings):
            total_earnings = sum(item['amount'] for item in earnings)

        total_deductions_from_concepts = sum(item['amount'] for item in deductions)

        if not currency.is_zero(total_earnings) and not currency.is_zero(net_amount):
            total_deductions = total_earnings - net_amount
        else:
            total_deductions = total_deductions_from_concepts

        if currency.is_zero(net_amount):
            net_amount = total_earnings - total_deductions

        return {
            'total_earnings': total_earnings,
            'total_deductions': abs(total_deductions),
            'net_amount': net_amount,
        }


    ### MOdelo Secunadrio principal para alimentar de datos a la nomina
    def _get_report_data(self, payslip):
        earnings = self._get_earnings(payslip)
        deductions = self._get_deductions(payslip)
        employer_contributions = self._get_employer_contributions(payslip)
        totals = self._get_totals(payslip, earnings, deductions)

        return {
            'employee': self._get_employee_data(payslip),
            'period': self._get_period_data(payslip),
            'earnings': earnings,
            'deductions': deductions,
            'employer_contributions': employer_contributions,
            'totals': totals,
        }

    #MAIN
    @api.model
    def _get_report_values(self, docids, data=None):
        """
        Método principal que Odoo llama cuando genera el PDF.
        """
        docs = self.env['hr.payslip'].browse(docids)

        report_data_by_id = {}

        for payslip in docs:
            report_data_by_id[payslip.id] = self._get_report_data(payslip)

        return {
            'doc_ids': docids,
            'doc_model': 'hr.payslip',
            'docs': docs,
            'report_data_by_id': report_data_by_id,
        }