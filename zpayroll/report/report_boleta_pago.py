    ## Relaciona y obtiene datos desde el modelo zemployee_extension
    def _get_employee_extension(self, employee):
       
        if not employee:
            return False

        return self.env['zemployee.extension'].sudo().search([
            ('employee_id', '=', employee.id)
        ], limit=1)



    def _get_selection_label(self, record, field_name):
        """
        Devuelve la etiqueta visible de un campo selection.
        Ejemplo: 'essalud_regular' -> 'ESSALUD REGULAR'
        """
        if not record or not field_name:
            return ''

        field = record._fields.get(field_name)
        if not field or not getattr(field, 'selection', False):
            return ''

        value = record[field_name]
        if not value:
            return ''

        return dict(field.selection).get(value, '')

    ## Obtiene datos de hr.payslip
    def _get_period_data(self, payslip):
        
        month_name = ''

        if payslip.payroll_month:
            month_name = dict(
                payslip._fields['payroll_month'].selection
            ).get(payslip.payroll_month, '')

        year = payslip.payroll_year or ''

        return {
            'month_name': month_name,
            'year': year,
            'period_name': '%s - %s' % (month_name, year) if month_name or year else '',
        }



    ##data para la estructura de la boelta
    def _get_employee_data(self, payslip):
        employee = payslip.employee_id
        contract = payslip.contract_id
        company = payslip.company_id
        emp_ext = self._get_employee_extension(employee)

        return {
            # Empresa
            'company_name': company.name or '',
            'company_vat': company.vat or '',

            # Código / contrato
            'contract_code': contract.code if contract and contract.code else '',
            'employee_code': employee.barcode or employee.id or '',

            # Trabajador
            'name': employee.name or '',
            'gender': employee.gender or '',
            'birthday': format_date(self.env, employee.birthday) if employee.birthday else '',
            'identification_id': employee.identification_id or '',
            'nationality': employee.country_id.name or '',

            # Fechas laborales desde zemployee.extension
            'entry_date': format_date(self.env, emp_ext.entry_date) if emp_ext and emp_ext.entry_date else '',
            'termination_date': format_date(self.env, emp_ext.termination_date) if emp_ext and emp_ext.termination_date else '',

            # Contrato
            'job': employee.job_id.name or '',
            'wage': contract.wage if contract else 0.0,
            'contract_type': contract.contract_type_id.name if contract and contract.contract_type_id else '',
            #'cost_center': contract.analytic_account_id.name if contract and contract.analytic_account_id else '',
            'special_situation': 'Ninguna',

            # Extensión peruana
            'essalud_autogenerated': '',
            'cuspp': emp_ext.cuspp if emp_ext else '',
            'afp': emp_ext.afp_id.name if emp_ext and emp_ext.afp_id else '',
            'pension_scheme': self._get_selection_label(emp_ext, 'pe_pension_scheme') if emp_ext else '',
            'health_scheme': self._get_selection_label(emp_ext, 'pe_health_scheme') if emp_ext else '',

            # Dirección
            'address': employee.private_street or '',
            'address2': employee.private_street2 or '',
            
            # Licencias / vacaciones para boleta
            'leave_type': '',
            'leave_start_date': '',
            'leave_end_date': '',
        }




    ################## coneptos de la nomina
    # Primera parte para los coneptos de nomina, revisa el cdoigo
    def _get_lines_by_codes(self, payslip, codes):
        if isinstance(codes, str):
            codes = [codes]

        return payslip.line_ids.filtered(lambda line: line.code in codes)

    # Sgunda, suma los motos totales para cada concpeto
    def _sum_line_codes(self, payslip, codes, absolute=False):
        lines = self._get_lines_by_codes(payslip, codes)
        amount = sum(lines.mapped('total')) or 0.0

        if absolute:
            amount = abs(amount)

        return amount


    def _get_concept(self, payslip, codes, name, section='earning', show_zero=False, qty_label=''):
        amount = self._sum_line_codes(
            payslip,
            codes,
            absolute=True if section == 'deduction' else False
        )

        currency = payslip.company_id.currency_id

        if not show_zero and currency.is_zero(amount):
            return False

        return {
            'name': name,
            'amount': amount,
            'qty_label': qty_label or '',
            'section': section,
        }


